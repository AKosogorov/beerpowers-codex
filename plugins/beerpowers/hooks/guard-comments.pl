use strict;
use warnings;
use utf8;

sub guard_comments {
    my ($repo, $cfg, $diff, $ranges) = @_;
    my @exclude = ref $cfg->{comments} eq 'HASH' && ref $cfg->{comments}{excludeDirs} eq 'ARRAY'
        ? @{$cfg->{comments}{excludeDirs}} : ();
    my ($name, @comments, @context);
    for my $line (map { split /\n/, git_read($repo, @$diff, '-U0', @$_) } @$ranges) {
        if ($line =~ /^diff --git /) { undef $name; next }
        if (!defined $name && $line =~ /^\+\+\+ b\/(.*?)\t?$/) {
            $name = $1;
            my $full = 'projects/' . basename($repo) . "/$name";
            $name = '' if grep { my $dir = $_; $dir =~ s{/$}{}; index($full, "$dir/") == 0 } @exclude;
            if ($name =~ m{^\.codex/} && -f "$repo/$name") {
                if (open my $source, '<:raw', "$repo/$name") {
                    my $header = '';
                    read $source, $header, 1024;
                    my @lines = split /\n/, $header, 4;
                    $name = '' if grep { defined && /generated by beerpowers v/i } @lines[0..2];
                }
            }
            next;
        }
        next unless $name && $line =~ /^\+(.*)$/;
        my $added = $1;
        my $slash = $name =~ /\.(?:tsx?|jsx?|mjs|cjs|vue|svelte|php|css|scss|less|go|java|kts?|swift|rs|c|h|cc|cpp|hpp|cs|scala|dart|html)$/i;
        my $hash = $name =~ /(?:\.(?:py|sh|bash|rb|pl|ps1|ya?ml|toml|php|exs?)|Dockerfile)$/i;
        my $comment;
        if ($slash && $added =~ m{(?:^|\s)(?://|/\*)|^\s*\*[^/]|<!--|\{\{--}) { $comment = substr($added, $-[0]) }
        if ($hash && $added =~ /(?:^\s*#(?![!\[])|\s#\s)/) {
            my $text = substr($added, $-[0]);
            $comment = $text if !defined($comment) || length($text) > length($comment);
        }
        next unless defined $comment;
        push @comments, "$name: $added";
        push @context, "$name: $comment" if $comment =~ m{\b[QCBRNSM]\d+\b|[Оо]твет\s+\d+|memory/tasks/};
    }
    return unless @comments;
    my $sum = sha256_hex(encode('UTF-8', join "\n", @comments));
    my $file = state_file('comments', $repo);
    return if seen($file, $sum);
    remember($file, $sum);
    my $note = @context ? "Ссылки на контекст задачи, который может исчезнуть после мержа:\n" .
        substr(join("\n", @context), 0, 1200) . "\n" : '';
    deny('guard-comments', $note . "Перечитай новые комментарии перед повтором коммита:\n" . substr(join("\n", @comments), 0, 3000));
}

1;
